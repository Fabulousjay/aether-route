
import os
from pathlib import Path
from urllib.parse import urlparse

BASE_DIR = Path(__file__).resolve().parent.parent

DEBUG = os.getenv("DJANGO_DEBUG", "False").lower() == "true"

SECRET_KEY = os.getenv("DJANGO_SECRET_KEY")

if not SECRET_KEY:
    if DEBUG:
        SECRET_KEY = "django-insecure-local-development-only"
    else:
        raise RuntimeError(
            "DJANGO_SECRET_KEY must be configured when DEBUG is disabled."
        )


def environment_list(name, default=""):
    return [
        value.strip()
        for value in os.getenv(name, default).split(",")
        if value.strip()
    ]


ALLOWED_HOSTS = environment_list(
    "DJANGO_ALLOWED_HOSTS",
    "localhost,127.0.0.1",
)

CORS_ALLOWED_ORIGINS = environment_list(
    "CORS_ALLOWED_ORIGINS",
    "http://localhost:5173,http://127.0.0.1:5173",
)

CSRF_TRUSTED_ORIGINS = environment_list(
    "CSRF_TRUSTED_ORIGINS",
)

render_hostname = os.getenv("RENDER_EXTERNAL_HOSTNAME")

if render_hostname and render_hostname not in ALLOWED_HOSTS:
    ALLOWED_HOSTS.append(render_hostname)

render_url = os.getenv("RENDER_EXTERNAL_URL")

if render_url:
    parsed_url = urlparse(render_url)

    if parsed_url.scheme and parsed_url.netloc:
        origin = f"{parsed_url.scheme}://{parsed_url.netloc}"

        if origin not in CSRF_TRUSTED_ORIGINS:
            CSRF_TRUSTED_ORIGINS.append(origin)


